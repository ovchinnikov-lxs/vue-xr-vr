// Generates the props / events / slots tables of every exported component
// from its TypeScript source (types, defaults and JSDoc comments), so the API
// reference can never drift from the code. Output: components/api/<Name>.md,
// included into the hand-written component pages with <!--@include: -->.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { createChecker } from 'vue-component-meta'

const here = dirname(fileURLToPath(import.meta.url))
const lib = join(here, '../../../packages/vue-xr-ui')
const componentsDir = join(lib, 'src/components')
const out = join(here, '../components/api')
mkdirSync(out, { recursive: true })

const checker = createChecker(join(lib, 'tsconfig.json'), { forceUseTs: true, printer: { newLine: 1 } })
// Vue's own attributes, present on every component.
const builtIn = new Set(['key', 'ref', 'ref_for', 'ref_key', 'class', 'style'])
const typeOf = (t) => t?.replace(/ \| undefined$/, '')

const cell = (s) => (s ?? '').toString().replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim()
const code = (s) => (s ? `<code>${cell(s).replace(/</g, '&lt;').replace(/>/g, '&gt;')}</code>` : '')

// vue-component-meta drops the JSDoc on entries of an `emits` object, so
// read `/** doc */ 'name': (...) => true` from the source.
const emitDocs = (source) => {
  const docs = new Map()
  const block = source.match(/emits:\s*\{([\s\S]*?)\n  \},/)
  if (!block) return docs
  for (const m of block[1].matchAll(/\/\*\*([\s\S]*?)\*\/\s*'?([\w:-]+)'?\s*:/g)) {
    docs.set(m[2], m[1].replace(/^\s*\* ?/gm, '').trim())
  }
  return docs
}

let count = 0
// Every public prop and event must say what it does: the table is the reference.
const undocumented = []
for (const file of readdirSync(componentsDir).filter((f) => f.endsWith('.ts'))) {
  const path = join(componentsDir, file)
  const events = emitDocs(readFileSync(path, 'utf8'))
  for (const name of checker.getExportNames(path).filter((n) => /^Xr[A-Z]/.test(n))) {
  let meta
  try {
    meta = checker.getComponentMeta(path, name)
  } catch {
    continue // a type export such as XrButtonVariant
  }
  if (meta.type === 0) continue
  const props = meta.props.filter((p) => !p.global && !builtIn.has(p.name) && !/^on[A-Z:]|^onVue:/.test(p.name))
  const lines = []
  lines.push('### Props', '')
  if (props.length) {
    lines.push('| Prop | Type | Default | Description |', '| --- | --- | --- | --- |')
    for (const p of props) {
      if (!p.description) undocumented.push(`${name} prop ${p.name}`)
      lines.push(`| \`${p.name}\`${p.required ? ' *' : ''} | ${code(typeOf(p.type))} | ${code(p.default)} | ${cell(p.description)} |`)
    }
  } else lines.push('None.')
  if (meta.events.length) {
    lines.push('', '### Events', '', '| Event | Payload | Description |', '| --- | --- | --- |')
    for (const e of meta.events) if (!(e.description || events.get(e.name))) undocumented.push(`${name} event ${e.name}`)
    for (const e of meta.events) lines.push(`| \`${e.name}\` | ${code(e.type?.replace(/^\[|\]$/g, '').replace(/(^|, )_/g, '$1'))} | ${cell(e.description || events.get(e.name))} |`)
  }
  if (meta.slots.length) {
    lines.push('', '### Slots', '', '| Slot | Description |', '| --- | --- |')
    for (const s of meta.slots) lines.push(`| \`${s.name}\` | ${cell(s.description)} |`)
  }
  writeFileSync(join(out, `${name}.md`), `<!-- Generated by scripts/api.mjs from the component source. Do not edit. -->\n\n${lines.join('\n')}\n`)
  count++
  }
}
console.log(`API tables: ${count} components -> components/api/`)
if (undocumented.length) {
  console.error(`No JSDoc (add a /** comment */ in the component source):\n  ${undocumented.join('\n  ')}`)
  process.exit(1)
}
